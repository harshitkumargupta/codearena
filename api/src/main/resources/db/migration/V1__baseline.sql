CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(16)  NOT NULL DEFAULT 'USER',
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT chk_users_role CHECK (role IN ('USER', 'ADMIN'))
);

CREATE TABLE problems (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug            VARCHAR(100) NOT NULL UNIQUE,
    title           VARCHAR(200) NOT NULL,
    statement_md    TEXT         NOT NULL,
    difficulty      VARCHAR(16)  NOT NULL,
    time_limit_ms   INT          NOT NULL,
    memory_limit_mb INT          NOT NULL,
    created_by      BIGINT       REFERENCES users (id),
    published       BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE test_cases (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    problem_id      BIGINT  NOT NULL REFERENCES problems (id) ON DELETE CASCADE,
    input           TEXT    NOT NULL,
    expected_output TEXT    NOT NULL,
    is_sample       BOOLEAN NOT NULL DEFAULT FALSE,
    ordinal         INT     NOT NULL
);

CREATE TABLE contests (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           VARCHAR(200) NOT NULL,
    start_time      TIMESTAMPTZ  NOT NULL,
    end_time        TIMESTAMPTZ  NOT NULL,
    penalty_minutes INT          NOT NULL DEFAULT 20,
    created_by      BIGINT       REFERENCES users (id),
    CONSTRAINT chk_contests_window CHECK (end_time > start_time)
);

CREATE TABLE contest_problems (
    contest_id BIGINT      NOT NULL REFERENCES contests (id) ON DELETE CASCADE,
    problem_id BIGINT      NOT NULL REFERENCES problems (id),
    label      VARCHAR(4)  NOT NULL,
    PRIMARY KEY (contest_id, problem_id),
    CONSTRAINT uq_contest_problems_label UNIQUE (contest_id, label)
);

CREATE TABLE contest_participants (
    contest_id BIGINT      NOT NULL REFERENCES contests (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES users (id),
    joined_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (contest_id, user_id)
);

CREATE TABLE submissions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT      NOT NULL REFERENCES users (id),
    problem_id          BIGINT      NOT NULL REFERENCES problems (id),
    contest_id          BIGINT      REFERENCES contests (id),
    language            VARCHAR(16) NOT NULL,
    source_code         TEXT        NOT NULL,
    status              VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    verdict_detail      TEXT,
    failed_test_ordinal INT,
    time_ms             INT,
    memory_kb           INT,
    attempts_count      INT         NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    judged_at           TIMESTAMPTZ,
    CONSTRAINT chk_submissions_language CHECK (language IN ('JAVA', 'PYTHON')),
    CONSTRAINT chk_submissions_status CHECK (status IN (
        'PENDING', 'RUNNING', 'ACCEPTED', 'WRONG_ANSWER', 'TIME_LIMIT_EXCEEDED',
        'MEMORY_LIMIT_EXCEEDED', 'RUNTIME_ERROR', 'COMPILATION_ERROR', 'INTERNAL_ERROR'))
);

CREATE TABLE hint_logs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT      NOT NULL REFERENCES users (id),
    problem_id    BIGINT      NOT NULL REFERENCES problems (id),
    submission_id BIGINT      REFERENCES submissions (id),
    level         SMALLINT    NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_submissions_user_created ON submissions (user_id, created_at DESC);
CREATE INDEX idx_submissions_contest_user_problem ON submissions (contest_id, user_id, problem_id);
CREATE INDEX idx_submissions_status ON submissions (status);
CREATE UNIQUE INDEX idx_test_cases_problem_ordinal ON test_cases (problem_id, ordinal);
